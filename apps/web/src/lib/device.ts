/**
 * Device class detection. TVs get a remote-first layout without live blur; phones get the
 * bottom bar. `?device=tv` forces TV mode for testing on a desktop browser.
 */
export type DeviceClass = 'tv' | 'desktop' | 'mobile';

export function detectDevice(): DeviceClass {
  const forced = new URLSearchParams(location.search).get('device') ?? sessionStorageGet('atlas.device');
  if (forced === 'tv' || forced === 'desktop' || forced === 'mobile') {
    sessionStorageSet('atlas.device', forced);
    return forced;
  }
  const ua = navigator.userAgent;
  // The ATLAS Android app tells us whether it runs on a TV (Android TV / Fire TV) or a phone.
  if (/AtlasApp\/[^ ]+ \(TV\)/.test(ua)) return 'tv';
  if (/Android TV|AFT[A-Z]|SMART-TV|SmartTV|Tizen|Web0S|webOS|BRAVIA|GoogleTV|CrKey|Fire TV|HbbTV/i.test(ua)) return 'tv';
  if (matchMedia('(pointer: coarse)').matches && Math.min(screen.width, screen.height) < 820) return 'mobile';
  return 'desktop';
}

function sessionStorageGet(key: string): string | null {
  try {
    return sessionStorage.getItem(key);
  } catch {
    return null;
  }
}
function sessionStorageSet(key: string, v: string): void {
  try {
    sessionStorage.setItem(key, v);
  } catch {
    /* private mode */
  }
}

export function storageGet<T>(key: string, fallback: T): T {
  try {
    const raw = localStorage.getItem(key);
    return raw === null ? fallback : (JSON.parse(raw) as T);
  } catch {
    return fallback;
  }
}

export function storageSet(key: string, value: unknown): void {
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch {
    /* quota or private mode */
  }
}

// TV remotes whose keys arrive as "Unidentified" with only a key code (older LG webOS).
const TV_KEY_CODES: Record<number, string> = {
  415: 'MediaPlay',
  19: 'MediaPause',
  413: 'MediaStop',
  417: 'MediaFastForward',
  412: 'MediaRewind',
  10252: 'MediaPlayPause',
};

/** `e.key`, with TV remote media keys filled in from their key codes when the browser leaves them blank. */
export function remoteKey(e: KeyboardEvent): string {
  if (e.key && e.key !== 'Unidentified') return e.key;
  return TV_KEY_CODES[e.keyCode] ?? e.key;
}

type WebOsSystem = { platformBack?: () => void };
const webOsSystem = (): WebOsSystem | undefined => {
  const w = window as unknown as { webOSSystem?: WebOsSystem; PalmSystem?: WebOsSystem };
  return w.webOSSystem ?? w.PalmSystem;
};

/** True inside the ATLAS app for LG webOS TVs, which opens this site in its own web view. */
export function inWebOsApp(): boolean {
  return !!webOsSystem();
}

/** Back on the LG app's first screen: hand over to the TV, which returns to its home screen. */
export function leaveWebOsApp(): void {
  const sys = webOsSystem();
  if (!sys) return;
  if (sys.platformBack) sys.platformBack();
  else window.close();
}

/**
 * Older TV browsers (Chromium < 84, e.g. LG webOS 5 and 6) ignore `gap` in flex layouts.
 * Flag them so the margin fallbacks generated by legacy-css.mjs apply.
 */
export function flagMissingFlexGap(): void {
  const box = document.createElement('div');
  box.style.cssText = 'display:flex;flex-direction:column;row-gap:1px;position:absolute;visibility:hidden';
  box.appendChild(document.createElement('div'));
  box.appendChild(document.createElement('div'));
  document.body.appendChild(box);
  const supported = box.scrollHeight === 1;
  box.remove();
  if (!supported) document.documentElement.classList.add('no-flexgap');
}

export function prefersReducedMotion(): boolean {
  return document.documentElement.dataset.motion === 'reduced' || matchMedia('(prefers-reduced-motion: reduce)').matches;
}

/** Track the last input modality so focus rings only show for keyboards and remotes. */
export function trackInputMode(): void {
  const root = document.documentElement;
  const set = (mode: string) => {
    if (root.dataset.input !== mode) root.dataset.input = mode;
  };
  window.addEventListener('keydown', (e) => {
    if (e.key.startsWith('Arrow') || e.key === 'Tab' || e.key === 'Enter') set('keys');
  }, { capture: true, passive: true });
  window.addEventListener('pointerdown', (e) => set(e.pointerType === 'touch' ? 'touch' : 'pointer'), { capture: true, passive: true });
  window.addEventListener('pointermove', (e) => {
    if (e.pointerType === 'mouse') set('pointer');
  }, { capture: true, passive: true });
}
